#!/usr/bin/env python3
"""
🏆 简单超级测试 - 6分钟
"""

import requests
import time
import random
import threading
import sys
import string
from datetime import datetime
from concurrent.futures import ThreadPoolExecutor
from collections import defaultdict

BASE_URL = "http://localhost:5174/api"

class SimpleMonitor:
    def __init__(self, duration_minutes=6):
        self.lock = threading.Lock()
        self.start_time = time.time()
        self.end_time = self.start_time + duration_minutes * 60
        
        self.total_requests = 0
        self.success_requests = 0
        self.failed_requests = 0
        self.critical_errors = []
        self.created_projects = []
        
        self.endpoint_stats = defaultdict(lambda: {'total': 0, 'success': 0, 'failed': 0})
    
    def log(self, message, level="INFO"):
        timestamp = datetime.now().strftime("%H:%M:%S")
        prefix = {"INFO": "ℹ️", "SUCCESS": "✅", "WARNING": "⚠️", "ERROR": "❌", "CRITICAL": "🚨"}
        print(f"[{timestamp}] [{prefix.get(level, '📄')}] {message}")
        if level == "CRITICAL":
            self.critical_errors.append(message)
    
    def record_request(self, endpoint, success):
        with self.lock:
            self.total_requests += 1
            self.endpoint_stats[endpoint]['total'] += 1
            if success:
                self.success_requests += 1
                self.endpoint_stats[endpoint]['success'] += 1
            else:
                self.failed_requests += 1
                self.endpoint_stats[endpoint]['failed'] += 1
    
    def print_status(self):
        with self.lock:
            elapsed = time.time() - self.start_time
            remaining = self.end_time - time.time()
            
            if self.total_requests > 0:
                success_rate = (self.success_requests / self.total_requests) * 100
            else:
                success_rate = 0
                
            print("\n" + "="*75)
            print(f"📊 - 已运行: {elapsed/60:.1f}min, 剩余: {remaining/60:.1f}min")
            print(f"📨 总请求: {self.total_requests:6} | ✅ 成功: {self.success_requests:6}")
            print(f"📈 成功率: {success_rate:5.1f}% | ❌ 失败: {self.failed_requests:6}")
            if self.critical_errors:
                print(f"🚨 严重错误: {len(self.critical_errors):4}")
            print("="*75)

def worker(worker_id, monitor):
    thread_name = f"W{worker_id:02d}"
    local_projects = []
    
    while time.time() < monitor.end_time and not monitor.stop_event.is_set():
        try:
            operation = random.choices(
                ['health', 'create', 'get', 'update', 'delete', 'browse', 'read', 'issues', 'extreme'],
                weights=[8, 18, 22, 14, 10, 10, 10, 5, 3]
            )[0]
            
            success = False
            endpoint = operation
            
            if operation == 'health':
                try:
                    r = requests.get(f"{BASE_URL}/health", timeout=30)
                    success = r.status_code == 200
                except:
                    pass
                    
            elif operation == 'create':
                try:
                    name = "test_" + str(random.randint(1, 1000000))
                    r = requests.post(f"{BASE_URL}/projects", 
                                      json={'name': name, 'path': '/workspace/path_test_system'}, 
                                      timeout=30)
                    
                    if r.status_code == 201:
                        try:
                            data = r.json()
                            if 'id' in data:
                                with monitor.lock:
                                    monitor.created_projects.append(data['id'])
                                local_projects.append(data['id'])
                                success = True
                        except:
                            pass
                except:
                    pass
                    
            elif operation == 'get':
                try:
                    r = requests.get(f"{BASE_URL}/projects", timeout=30)
                    success = r.status_code == 200
                except:
                    pass
                    
            elif operation == 'update':
                if local_projects:
                    try:
                        pid = random.choice(local_projects)
                        new_name = "updated_" + str(random.randint(1, 1000000))
                        r = requests.put(f"{BASE_URL}/projects/{pid}", 
                                        json={'name': new_name}, 
                                        timeout=30)
                        success = r.status_code in [200, 204]
                    except:
                        pass
                        
            elif operation == 'delete':
                if local_projects:
                    try:
                        pid = local_projects.pop(0)
                        r = requests.delete(f"{BASE_URL}/projects/{pid}", timeout=30)
                        success = r.status_code in [200, 204, 404]
                        
                        if success:
                            with monitor.lock:
                                if pid in monitor.created_projects:
                                    monitor.created_projects.remove(pid)
                    except:
                        pass
                        
            elif operation == 'browse':
                try:
                    r = requests.get(f"{BASE_URL}/files/browse", params={'path': '/workspace'}, timeout=30)
                    success = r.status_code in [200, 403]
                except:
                    pass
                    
            elif operation == 'read':
                try:
                    r = requests.get(f"{BASE_URL}/files/read", 
                                    params={'path': '/workspace/path_test_system/requirements.txt'}, 
                                    timeout=30)
                    success = r.status_code in [200, 404]
                except:
                    pass
                    
            elif operation == 'issues':
                try:
                    r = requests.get(f"{BASE_URL}/issues", timeout=30)
                    success = r.status_code == 200
                except:
                    pass
                    
            elif operation == 'extreme':
                try:
                    if random.random() < 0.5:
                        fake_id = "nonexistent_" + ''.join(random.choices(string.ascii_letters, k=20))
                        r = requests.get(f"{BASE_URL}/projects/{fake_id}", timeout=30)
                        success = r.status_code == 404
                    else:
                        r = requests.post(f"{BASE_URL}/projects", json={}, timeout=30)
                        success = r.status_code in [400, 404]
                except:
                    pass
                    
            monitor.record_request(endpoint, success)
            time.sleep(random.uniform(0.02, 0.15))
            
        except Exception as e:
            monitor.log(f"{thread_name} 异常: {str(e)}", "WARNING")
    
    for pid in local_projects:
        try:
            requests.delete(f"{BASE_URL}/projects/{pid}", timeout=20)
        except:
            pass

def main():
    print("="*75)
    print("🏆 简单超级测试 - 开始")
    print("="*75)
    print(f"⏱️  测试时长: 6分钟")
    print(f"👷 并发线程: 12个")
    print("="*75)
    
    monitor = SimpleMonitor(duration_minutes=6)
    monitor.stop_event = threading.Event()
    
    print("\n🚀 启动线程...")
    with ThreadPoolExecutor(max_workers=12) as executor:
        futures = [executor.submit(worker, i, monitor) for i in range(12)]
        
        last_print = time.time()
        while time.time() < monitor.end_time:
            time.sleep(0.5)
            
            if time.time() - last_print >= 45:
                monitor.print_status()
                last_print = time.time()
        
        print("\n⏳ 等待完成...")
        monitor.stop_event.set()
        for f in futures:
            f.result()
    
    print("\n🧹 清理项目...")
    with monitor.lock:
        projects = list(monitor.created_projects)
    
    for pid in projects:
        try:
            requests.delete(f"{BASE_URL}/projects/{pid}", timeout=20)
        except:
            pass
    
    # 最终报告
    elapsed = time.time() - monitor.start_time
    success_rate = (monitor.success_requests / monitor.total_requests * 100) if monitor.total_requests > 0 else 0
    
    print("\n" + "="*75)
    print("🏆 最终报告")
    print("="*75)
    print(f"⏱️  时长: {elapsed/60:.2f}分钟")
    print(f"📨 总请求: {monitor.total_requests}")
    print(f"✅ 成功: {monitor.success_requests}")
    print(f"❌ 失败: {monitor.failed_requests}")
    print(f"📈 成功率: {success_rate:.2f}%")
    print()
    print("🔍 端点统计:")
    for endpoint, stats in monitor.endpoint_stats.items():
        ep_success_rate = (stats['success']/stats['total']*100) if stats['total'] > 0 else 0
        print(f"  {endpoint:10} {stats['total']:5}次, {stats['success']:5}成功, {ep_success_rate:6.1f}%")
    
    print()
    if monitor.critical_errors:
        print("🚨 严重错误:")
        for err in monitor.critical_errors[:10]:
            print(f"  {err}")
        print()
    
    if success_rate >= 95 and len(monitor.critical_errors) == 0:
        print("🎯 评级: 优秀！")
    elif success_rate >= 90:
        print("🎯 评级: 良好")
    else:
        print("🎯 评级: 需要关注")
    print("="*75)
    
    return len(monitor.critical_errors) == 0

if __name__ == "__main__":
    try:
        result = main()
        sys.exit(0 if result else 1)
    except KeyboardInterrupt:
        print("\n\n⏹️ 测试中断")
        sys.exit(1)
